#!/bin/bash
set -e

MODULE=$1

if [ -n "$MODULE" ]; then
    echo "======================================================================"
    echo " 正在使用本地已编译依赖打包单模块镜像: $MODULE"
    echo "======================================================================"
    docker compose build "$MODULE"
    echo "======================================================================"
    echo " $MODULE 镜像打包完成！"
    echo " 启动服务: docker compose up -d --no-deps $MODULE"
    echo " 推送镜像: docker compose push $MODULE"
    echo "======================================================================"
else
    echo "======================================================================"
    echo " 正在使用本地已编译依赖打包全部微服务镜像..."
    echo "======================================================================"
    docker compose build
    echo "======================================================================"
    echo " 全部微服务镜像打包完成！"
    echo " 一键启动命令: docker compose up -d"
    echo " 一键推送全部镜像: docker compose push"
    echo " 查看日志命令: docker compose logs -f"
    echo "======================================================================"
fi
